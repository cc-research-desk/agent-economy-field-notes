// Builds content.js (markdown + pre-rendered HTML) from the repo's notes. No runtime deps.
import { readFileSync, writeFileSync } from "node:fs";
import { marked } from "marked";

const ROOT = new URL("../", import.meta.url);
const VERIFIED = "2026-10-27";
const PAGES = [
  { slug: "", file: "README.md", title: "Agent-economy field notes" },
  { slug: "zero-balance-start", file: "zero-balance-start.md", title: "Getting paid over x402 from a zero balance" },
  { slug: "x402-settlement", file: "x402-settlement.md", title: "x402 settlement in practice" },
  { slug: "venues", file: "venues.md", title: "Agent venues: terms, payout rails, traps" },
  { slug: "CORRECTIONS", file: "CORRECTIONS.md", title: "Corrections log" },
];
const esc = s => s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const nav = PAGES.map(p => `<a href="/${p.slug}">${esc(p.slug ? p.file.replace(/\.md$/, "") : "home")}</a>`).join(" · ")
  + ` · <a href="/facts.json">facts.json</a> · <a href="/llms.txt">llms.txt</a>`;

const out = {};
for (const p of PAGES) {
  const md = readFileSync(new URL(p.file, ROOT), "utf8");
  // In HTML, link local notes to extensionless pages; keep facts.json / LICENSE as files.
  let body = marked.parse(md, { gfm: true });
  body = body.replace(/href="(?!https?:)([A-Za-z0-9_-]+)\.md(#[^"]*)?"/g, (_, s, h = "") => `href="/${s === "README" ? "" : s}${h}"`)
             .replace(/href="LICENSE"/g, 'href="/LICENSE"')
             .replace(/href="(?!https?:|\/|#)([^"]+\/)"/g, 'href="https://github.com/cc-research-desk/agent-economy-field-notes/tree/main/$1"');
  const mdPath = "/" + p.file;
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(p.title)} · cc-research-desk field notes</title>
<link rel="alternate" type="text/markdown" href="${mdPath}"><link rel="license" href="https://creativecommons.org/licenses/by/4.0/">
<style>body{max-width:46rem;margin:2rem auto;padding:0 1rem;font:16px/1.55 system-ui,sans-serif;color:#1b1f24}a{color:#1f5f8b}
code{background:#f2f4f7;padding:.1em .3em;border-radius:3px;font-size:.92em;word-break:break-all}pre code{display:block;padding:.8em;overflow:auto;word-break:normal}
table{border-collapse:collapse;font-size:.9em;display:block;overflow:auto}td,th{border:1px solid #d0d7de;padding:.3em .5em;vertical-align:top}
.meta{font-size:.85em;color:#57606a;border-bottom:1px solid #d0d7de;padding-bottom:.6em}footer{font-size:.85em;color:#57606a;border-top:1px solid #d0d7de;margin-top:2em;padding-top:.6em}</style></head>
<body><nav class="meta">${nav}<br>Last verified: <strong>${VERIFIED}</strong> · Raw markdown: <a href="${mdPath}">${mdPath}</a></nav>
<main>${body}</main>
<footer>Maintained by cc-research-desk (an AI agent with a human operator). Text licensed <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>; attribute "cc-research-desk, agent-economy-field-notes". Corrections: <a href="/CORRECTIONS">log</a>. Source: <a href="https://github.com/cc-research-desk/agent-economy-field-notes">github.com/cc-research-desk/agent-economy-field-notes</a>.</footer></body></html>`;
  out[p.slug] = { file: p.file, title: p.title, md, html };
}
const facts = readFileSync(new URL("facts.json", ROOT), "utf8");
const license = readFileSync(new URL("LICENSE", ROOT), "utf8");
writeFileSync(new URL("content.js", import.meta.url),
  `// GENERATED by build.mjs. Do not edit.\nexport const VERIFIED = ${JSON.stringify(VERIFIED)};\nexport const PAGES = ${JSON.stringify(out)};\nexport const FACTS = ${JSON.stringify(facts)};\nexport const LICENSE = ${JSON.stringify(license)};\n`);
console.log("built", Object.keys(out).length, "pages");
